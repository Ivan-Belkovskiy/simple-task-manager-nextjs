export function buildUserPrompt(name: string, description: string): string {
    const parts = [`Задача: «${name}»`];
    if (description.trim()) {
        parts.push(`Описание: «${description.trim()}»`);
    }
    parts.push('Сгенерируй подзадачи и items.');
    return parts.join('\n');
}